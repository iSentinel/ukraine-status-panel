#!/usr/bin/env python3
"""Build and check Wi-Fi-only captive portal gzip/Brotli assets."""

import argparse
import gzip
import os
import re
import shutil
import subprocess
from pathlib import Path

from loguru import logger

ROOT = Path(__file__).resolve().parents[1]


def node_binary(explicit):
    """Use configured Node.js, a standard install, or the existing QA runtime."""
    candidate = explicit or os.environ.get("NODE_BIN") or shutil.which("node")
    if candidate:
        return str(candidate)
    bundled = ROOT.parent / ".qa-tools/node/bin/node"
    if bundled.is_file():
        return str(bundled)
    raise RuntimeError("Node.js is required; pass --node or set NODE_BIN")


def brotli(data, node, decompress=False):
    """Use Node's built-in codec without adding a package dependency."""
    operation = "brotliDecompressSync" if decompress else "brotliCompressSync"
    options = (
        ""
        if decompress
        else ",{params:{[z.constants.BROTLI_PARAM_QUALITY]:11}}"
    )
    code = (
        "const z=require('node:zlib'),fs=require('node:fs');"
        "process.stdout.write(z."
        + operation
        + "(fs.readFileSync(0)"
        + options
        + "));"
    )
    result = subprocess.run(
        [node, "-e", code], input=data, capture_output=True, check=True
    )
    return result.stdout


def validate_html(text):
    """Preserve Wi-Fi setup and reject any firmware upload control."""
    assert "/update" not in text.lower()
    assert "type=file" not in text.lower()
    for token in (
        "config.json",
        "/wifisave",
        "id=ssid",
        "name=psk",
        "type=password",
    ):
        assert token in text, token


def payloads(text):
    """Read the two actual C++ byte arrays without compiling platform code."""
    matches = re.findall(
        r"constexpr uint8_t (INDEX_GZ|INDEX_BR)\[\] PROGMEM = \{(.*?)\};",
        text,
        re.S,
    )
    result = {
        name: bytes(
            int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})", body)
        )
        for name, body in matches
    }
    assert set(result) == {"INDEX_GZ", "INDEX_BR"}
    return result


def array(name, data):
    """Render a small readable C++ array."""
    rows = []
    for offset in range(0, len(data), 16):
        rows.append(
            "    "
            + ", ".join(
                f"0x{value:02x}" for value in data[offset : offset + 16]
            )
            + ","
        )
    return (
        f"constexpr uint8_t {name}[] PROGMEM = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def generate(data, node):
    """Create both supported encodings while keeping the existing C++ interface."""
    return (
        "#pragma once\n// Generated by scripts/build-portal-assets.py.\n"
        '#include "esphome/core/hal.h"\n\n'
        "namespace esphome::captive_portal {\n"
        "#ifdef USE_CAPTIVE_PORTAL_GZIP\n"
        + array("INDEX_GZ", gzip.compress(data, mtime=0))
        + "#else\n"
        + array("INDEX_BR", brotli(data, node))
        + "#define INDEX_GZ INDEX_BR\n#endif\n"
        "}  // namespace esphome::captive_portal\n"
    )


def main():
    """Generate explicitly or verify semantic equality of checked-in encodings."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--html",
        type=Path,
        default=ROOT / "components/captive_portal/portal.html",
    )
    parser.add_argument(
        "--header",
        type=Path,
        default=ROOT / "components/captive_portal/captive_index.h",
    )
    parser.add_argument("--node")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.html.read_bytes()
    validate_html(data.decode())
    node = node_binary(args.node)
    if args.check:
        assets = payloads(args.header.read_text())
        assert gzip.decompress(assets["INDEX_GZ"]) == data
        assert brotli(assets["INDEX_BR"], node, decompress=True) == data
    else:
        args.header.write_text(generate(data, node))
    logger.info("PORTAL_ASSETS=PASS WiFi-only gzip/Brotli; no upload form")


if __name__ == "__main__":
    main()
