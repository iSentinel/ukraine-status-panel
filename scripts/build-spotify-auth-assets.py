#!/usr/bin/env python3
"""Generate deterministic flash gzip files for the private Spotify setup page."""

import argparse
import gzip
import io
import json
from pathlib import Path

from loguru import logger

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "index.html": "INDEX",
    "page.js": "PAGE_JS",
    "page.css": "PAGE_CSS",
    "return.js": "RETURN_JS",
}
BUDGET = 16384


def gzip_bytes(data):
    """Keep timestamps, filenames and host-dependent gzip metadata fixed."""
    stream = io.BytesIO()
    with gzip.GzipFile(
        fileobj=stream, mode="wb", filename="", mtime=0
    ) as file:
        file.write(data)
    return stream.getvalue()


def generated(source, channel):
    """Put immutable arrays in ESP32 flash; do not allocate an asset in RAM."""
    blocks = [
        "// Generated by scripts/build-spotify-auth-assets.py; do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "namespace esphome::usp_spotify_auth::assets {",
    ]
    sizes = {}
    for filename, symbol in FILES.items():
        data = (
            channel if filename == "return.js" else source / filename
        ).read_bytes()
        payload = gzip_bytes(data)
        assert gzip.decompress(payload) == data
        sizes[filename] = {"raw": len(data), "gzip": len(payload)}
        rows = [
            "  " + ", ".join(f"0x{byte:02x}" for byte in payload[i : i + 16])
            for i in range(0, len(payload), 16)
        ]
        blocks.extend(
            [
                f"inline constexpr uint8_t {symbol}[] = {{",
                ",\n".join(rows),
                "};",
            ]
        )
    total = sum(item["gzip"] for item in sizes.values())
    if total > BUDGET:
        raise ValueError(f"Spotify setup gzip size {total} exceeds {BUDGET}")
    blocks.append("}  // namespace esphome::usp_spotify_auth::assets")
    return "\n".join(blocks) + "\n", sizes


def main():
    """Check checked-in bytes or explicitly rebuild them without network I/O."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir", type=Path, default=ROOT / "firmware/webui/spotify-auth"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "components/usp_spotify_auth/assets.h",
    )
    parser.add_argument(
        "--channel",
        type=Path,
        default=ROOT / "firmware/webui/usp-spotify-auth-return.js",
    )
    parser.add_argument("--report", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, sizes = generated(args.source_dir, args.channel)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != content:
            raise ValueError("Spotify setup assets differ; regenerate them")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(content)
    if args.report:
        args.report.write_text(json.dumps(sizes, indent=2) + "\n")
    logger.info(
        "SPOTIFY_AUTH_ASSETS=PASS {} gzip bytes",
        sum(item["gzip"] for item in sizes.values()),
    )


if __name__ == "__main__":
    main()
